def get_product(product_type):
    """按设备类型取出目录配置，不存在返回 None。"""
    return DEVICE_CATALOG.get(product_type)


def get_action(product_type, service_id):
    """按设备类型 + serviceId 取出指令配置，不存在返回 None。"""
    product = DEVICE_CATALOG.get(product_type)
    if not product:
        return None
    for action in product.get("actions", []):
        if str(action.get("serviceId")) == str(service_id):
            return action
    return None


def build_catalog_payload(host, host_options=None):
    """
    组装前端需要的目录结构。

    统一转成 camelCase，避免前端再做字段映射。
    """
    product_types = []
    for value, product in DEVICE_CATALOG.items():
        product_types.append(
            {
                "value": value,
                "label": product.get("label", value),
                "description": product.get("description", ""),
                "actions": [
                    {
                        "serviceId": action.get("serviceId"),
                        "label": action.get("label", ""),
                        "description": action.get("description", ""),
                        "params": [
                            {
                                "key": param.get("key"),
                                "label": param.get("label", param.get("key")),
                                "type": param.get("type", "text"),
                                "required": bool(param.get("required", False)),
                                "placeholder": param.get("placeholder", ""),
                                "default": param.get("default", ""),
                                "range": param.get("range", ""),
                                "definition": param.get("definition", ""),
                                "range": param.get("range", ""),
                                "definition": param.get("definition", ""),
                            }
                            for param in action.get("params", [])
                        ],
                    }
                    for action in product.get("actions", [])
                ],
            }
        )

    return {
        "host": host,
        "hostOptions": host_options or [host],
        "pathTemplate": DEVICE_ACTION_PATH_TEMPLATE,
        "productTypes": product_types,
    }
